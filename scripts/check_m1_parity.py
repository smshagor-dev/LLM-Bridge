#!/usr/bin/env python3
"""Compare real model-derived output bytes against the pinned upstream reference."""
import argparse
import hashlib
import json
import os
import platform
import subprocess
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("--ours", required=True)
parser.add_argument("--reference", required=True)
parser.add_argument("--output", required=True)
args = parser.parse_args()
ours = Path(args.ours).read_bytes()
reference = Path(args.reference).read_bytes()
# The upstream simple example writes the original prompt before the generation.
# The Bridge CLI streams only the generated pieces followed by a newline.
passed = bool(ours.strip()) and reference.endswith(ours)
result = {
    "pass": passed,
    "comparison": "exact suffix of raw greedy output bytes",
    "bridge_output_hex": ours.hex(),
    "reference_output_sha256": hashlib.sha256(reference).hexdigest(),
    "host": platform.platform(),
    "git_sha": subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip(),
    "model": "ggml-org/tiny-llamas/stories15M-q8_0.gguf",
    "model_sha256": "2eda49203f2f044f3dddf29a7dd7cc861ef5a0340f518a19613d73ba6d9c06b6",
    "upstream": "llama.cpp v0.9.0",
}
Path(args.output).write_text(json.dumps(result, indent=2), encoding="utf-8")
if not passed:
    raise SystemExit("M1 parity FAIL: actual generated bytes differ from pinned upstream reference")
print("M1 parity PASS (actual generated byte suffix equals upstream reference)")

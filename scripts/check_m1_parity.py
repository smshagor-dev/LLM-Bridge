#!/usr/bin/env python3
"""Compare complete generation bytes, with an explicit reference prompt prefix."""
import argparse
import hashlib
import json
import platform
import subprocess
from pathlib import Path


def compare(ours, reference, prefix):
    # Strip exactly the declared framing, never a suffix chosen from our output.
    if not reference.startswith(prefix):
        return False
    expected = reference[len(prefix):]
    return bool(ours.strip()) and ours == expected


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--ours', required=True)
    parser.add_argument('--reference', required=True)
    parser.add_argument('--reference-prefix', required=True,
                        help='Exact bytes printed before reference generation (UTF-8)')
    parser.add_argument('--output', required=True)
    args = parser.parse_args()
    ours = Path(args.ours).read_bytes()
    reference = Path(args.reference).read_bytes()
    passed = compare(ours, reference, args.reference_prefix.encode('utf-8'))
    result = {
        'pass': passed,
        'comparison': 'complete generation bytes after exact declared prompt prefix',
        'reference_prefix': args.reference_prefix,
        'bridge_output_hex': ours.hex(),
        'reference_output_sha256': hashlib.sha256(reference).hexdigest(),
        'host': platform.platform(),
        'git_sha': subprocess.run(['git', 'rev-parse', 'HEAD'], capture_output=True,
                                  text=True, check=True).stdout.strip(),
        'model': 'ggml-org/tiny-llamas/stories15M-q8_0.gguf',
        'model_sha256': '2eda49203f2f044f3dddf29a7dd7cc861ef5a0340f518a19613d73ba6d9c06b6',
        'upstream': 'llama.cpp v0.9.0',
    }
    Path(args.output).write_text(json.dumps(result, indent=2), encoding='utf-8')
    if not passed:
        raise SystemExit('M1 parity FAIL: complete generated bytes differ from reference')
    print('M1 parity PASS (complete generation bytes equal reference)')


if __name__ == '__main__':
    main()
